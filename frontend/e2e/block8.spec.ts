import {test,expect} from '@playwright/test';
const api='http://127.0.0.1:18088/api/v1';
const reactWarnings=new WeakMap<object,string[]>();
test.beforeAll(()=>{if(process.env.BLOCK8_SYNTHETIC!=='true')throw Error('Requires disposable Block 8 database and backend on port 18088');});
test.beforeEach(async({page})=>{
 const warnings:string[]=[];reactWarnings.set(page,warnings);
 page.on('console',message=>{if(/same key|unique.*key|cannot be a descendant|validateDOMNesting/i.test(message.text()))warnings.push(message.text());});
 await page.addInitScript(()=>localStorage.setItem('ceroa_onboarding_seen','true'));
 await page.goto('/');await page.getByLabel('Correo electrónico').fill('demo@ceroa.local');
 await page.getByLabel('Contraseña',{exact:true}).fill('Demo123!');await page.getByRole('button',{name:'Iniciar sesión',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Hola, Mateo.'})).toBeVisible();
 await expect(page.getByRole('main')).toHaveCount(1);
});
test.afterEach(async({page})=>{expect(reactWarnings.get(page)).toEqual([]);});
test('React debt create, validation, update, reload and delete reach real PostgreSQL',async({page,context})=>{
 const name=`Block8 UI ${Date.now()}`;
 await page.getByRole('button',{name:'Deudas',exact:true}).first().click();
 await page.getByRole('button',{name:'Agregar deuda',exact:true}).first().click();
 await page.getByRole('button',{name:'Registrar obligación',exact:true}).click();
 await expect(page.getByText('El nombre personalizado es obligatorio',{exact:false})).toBeVisible();
 await page.getByLabel(/Tipo de obligación financiera/).selectOption('family_loan');
 await page.getByLabel(/Nombre personalizado/).fill(name);await page.getByLabel(/Acreedor o persona/).fill('Acreedor sintético');
 await page.getByLabel(/Saldo actual \(COP\)/).fill('100000');await page.locator('#debt-original-amount-input').fill('100000');
 await page.locator('#monthly-payment-input').fill('10000');
 const created=page.waitForResponse(r=>r.url()===api+'/debts'&&r.request().method()==='POST');
 await page.getByRole('button',{name:'Registrar obligación',exact:true}).click();
 const response=await created;expect(response.status()).toBe(201);const debt=await response.json();
 expect((await (await context.request.get(api+'/debts/'+debt.id)).json()).currentBalance).toBe(100000);
 await page.getByRole('heading',{name,exact:true,level:3}).click();await page.getByRole('button',{name:'Editar deuda',exact:true}).first().click();
 await page.getByLabel(/Nombre personalizado/).fill(name+' editada');
 const updated=page.waitForResponse(r=>r.url()===api+'/debts/'+debt.id&&r.request().method()==='PUT');
 await page.getByRole('button',{name:'Guardar cambios',exact:true}).click();expect((await updated).status()).toBe(200);
 await page.reload();expect((await (await context.request.get(api+'/debts/'+debt.id)).json()).name).toBe(name+' editada');
 await page.getByRole('button',{name:'Deudas',exact:true}).first().click();await page.getByRole('heading',{name:name+' editada',exact:true,level:3}).click();
 await page.getByRole('button',{name:'Eliminar deuda',exact:true}).click();
 const removed=page.waitForResponse(r=>r.url()===api+'/debts/'+debt.id&&r.request().method()==='DELETE');
 await page.getByRole('button',{name:'Eliminar definitivamente',exact:true}).click();expect((await removed).status()).toBe(204);
 expect((await context.request.get(api+'/debts/'+debt.id)).status()).toBe(404);
});
test('React payment commits principal and balance, and survives reload',async({page,context})=>{
 const csrf=await (await context.request.get(api+'/auth/csrf')).json();
 const name=`Block8 payment ${Date.now()}`;
 const result=await context.request.post(api+'/debts',{headers:{'X-XSRF-TOKEN':csrf.token},data:{name,type:'family_loan',originalAmount:100000,currentBalance:100000,rateType:'NONE',monthlyPayment:10000}});
 expect(result.status()).toBe(201);const debt=await result.json();await page.reload();
 await page.getByRole('button',{name:'Deudas',exact:true}).first().click();await page.getByRole('heading',{name,exact:true,level:3}).click();
 await page.getByRole('button',{name:'Registrar pago',exact:true}).click();await page.getByRole('radio',{name:'Abono adicional',exact:true}).click();
 await page.getByLabel(/Valor del pago/).fill('10000');
 const saved=page.waitForResponse(r=>r.url()===api+'/payments'&&r.request().method()==='POST');
 await page.getByRole('button',{name:'Confirmar pago',exact:true}).click();expect((await saved).status()).toBe(201);
 await page.reload();const persisted=await (await context.request.get(api+'/debts/'+debt.id)).json();expect(persisted.currentBalance).toBe(90000);
 const payments=await (await context.request.get(api+'/payments')).json();expect(payments.some((p:{debtId:string,amount:number})=>p.debtId===debt.id&&p.amount===10000)).toBe(true);
 await page.screenshot({path:'test-results/block8-payment.png',fullPage:true});
});
test('React strategy update survives reload and assistant reads fresh strategy without a provider',async({page,context})=>{
 await page.getByRole('button',{name:'Estrategia',exact:true}).first().click();
 const current=await (await context.request.get(api+'/strategies/active')).json();
 const target=current.activeStrategy==='snowball'?'avalanche':'snowball';const label=target==='snowball'?'Bola de Nieve':'Avalancha';
 const changed=page.waitForResponse(r=>r.url().includes('/strategies/active')&&r.request().method()==='PUT');
 await page.getByRole('radio',{name:new RegExp(label)}).click();expect((await changed).status()).toBe(200);
 await page.reload();await page.getByRole('button',{name:'Estrategia',exact:true}).first().click();
 await expect(page.getByRole('radio',{name:new RegExp(label)})).toHaveAttribute('aria-checked','true');
 const csrf=await (await context.request.get(api+'/auth/csrf')).json();const answer=await context.request.post(api+'/assistant/messages',{headers:{'X-XSRF-TOKEN':csrf.token},data:{message:'¿Qué estrategia de pago tengo activa?'}});
 expect(answer.status()).toBe(200);expect((await answer.json()).answer).toContain(label);await page.screenshot({path:'test-results/block8-strategy.png',fullPage:true});
});
